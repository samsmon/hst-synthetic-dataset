"""Build docs/data-dictionary.md from a database that has sql/01..04 applied.

Usage (connection through the usual PG* environment variables or flags):

    python scripts/build_dictionary.py [--host H] [--port P] [--user U] [--db D]

Types and nullability come from the catalog; descriptions come from the
COMMENT ON statements in sql/04_comments.sql. Only the psql client is needed.
"""
import argparse
import subprocess
from pathlib import Path

SEP = "\x1f"
QUERY = """
SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod),
       CASE WHEN a.attnotnull THEN 'no' ELSE 'yes' END,
       coalesce(col_description(c.oid, a.attnum), ''),
       coalesce(obj_description(c.oid, 'pg_class'), '')
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
WHERE n.nspname = '{schema}' AND c.relkind IN ('r', 'm')
ORDER BY c.relname, a.attnum
"""


def fetch(args, schema):
    cmd = ["psql", "-h", args.host, "-p", str(args.port), "-U", args.user,
           "-d", args.db, "-At", "-F", SEP, "-c", QUERY.format(schema=schema)]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return [line.split(SEP) for line in out.splitlines() if line]


def render(schema, rows):
    lines = [f"## Schema `{schema}`", ""]
    current = None
    for table, col, typ, nullable, col_comment, tab_comment in rows:
        if table != current:
            current = table
            lines += ["", f"### `{table}`", ""]
            if tab_comment:
                lines += [tab_comment, ""]
            lines += ["| Column | Type | Null | Description |", "|---|---|---|---|"]
        lines.append(f"| `{col}` | {typ} | {nullable} | {col_comment} |")
    return lines + [""]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--host", default="localhost")
    p.add_argument("--port", type=int, default=5432)
    p.add_argument("--user", default="postgres")
    p.add_argument("--db", default="postgres")
    args = p.parse_args()

    out = ["# Data dictionary", "",
           "Generated by `scripts/build_dictionary.py`. Do not edit by hand: change "
           "`sql/04_comments.sql` and run the script again.", ""]
    for schema in ("oltp", "dwh"):
        out += render(schema, fetch(args, schema))
    target = Path(__file__).resolve().parent.parent / "docs" / "data-dictionary.md"
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
